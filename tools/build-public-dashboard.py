"""Builds public/index.html — the ONLY thing published to GitHub Pages.

This is a deliberately reduced dashboard: sourcing/scan-results and the
manual Facebook checklist only. It never touches data/pieces.json,
data/materials.json, data/suppliers.json, data/piece_costings.json, or
research/ — those hold real supplier prices, piece costings, and buy
strategy notes and must never end up in a public repo or on a public
Pages URL. If you need a field from those files on the public page, stop
and ask first — don't just import them here.

Run after tools/build-dashboard.py, or standalone:
    python3 tools/build-public-dashboard.py
"""
