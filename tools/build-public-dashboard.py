def dedupe_variants(terms):
    seen_base = set()
    out = []
    for t in terms:
        base = t.lower().replace("-", " ").replace("ø", "o").replace("å", "a").replace("æ", "ae")
        base = "".join(c for c in base if c.isalnum() or c == " ")
        if base in seen_base:
            continue
        seen_base.add(base)
        out.append(t)
    return out


def format_scan_ends_at(value):
    if not value:
        return "—"
    try:
        if isinstance(value, str) and value.isdigit():
            value = int(value)
        if isinstance(value, (int, float)):
            dt = datetime.datetime.fromtimestamp(value)
        else:
            dt = datetime.datetime.fromisoformat(value)
        return dt.strftime("%d %b")
    except (ValueError, OSError, TypeError):
        return "—"


SCAN_SRC_LABEL = {"auctionet": "Auctionet", "tradera": "Tradera", "bukowskis": "Bukowskis", "haraldssons": "Haraldssons"}


def main():
    esc = html.escape
    kw = load_keywords()
    scan_lots, scan_total = load_scan_results()

    def scan_card(lot):
        price = lot.get("current_bid")
        price_html = (
            f'<div class="scanprice">{int(price):,} kr</div>'.replace(",", " ")
            if price
            else '<div class="scanprice scanprice-empty">no bid</div>'
        )
        flag = '<span class="scanflag">🚩</span>' if (lot.get("bad_listing_score") or 0) >= 3 else ""
        img = lot.get("image_url")
        img_html = f'<img src="{esc(img)}" alt="" loading="lazy">' if img else ""
        lot_key = f'{lot.get("source")}-{lot.get("lot_id")}'
        return (
            f'<div class="card scancard" data-state="new" data-lot-key="{esc(lot_key)}">'
            f'<div class="scanimgwrap fig ar-4-3">{img_html}{price_html}</div>'
            '<div class="scanbody">'
            '<div class="scantop">'
            f'{flag}<span class="tag">{esc(SCAN_SRC_LABEL.get(lot.get("source"), lot.get("source") or ""))}</span>'
            f'<span class="scanends text-muted">ends {esc(format_scan_ends_at(lot.get("ends_at")))}</span>'
            '</div>'
            f'<a class="scantitle" href="{esc(lot.get("url") or "#")}" target="_blank" rel="noopener">{esc(lot.get("title") or "Untitled lot")}</a>'
            f'<div class="text-muted scanmeta">matched "{esc(lot.get("matched_keyword") or "")}"</div>'
            '<div class="scanactions">'
            '<button class="btn btn-secondary scanbtn scanbtn-love" data-action="love" type="button">♡ Love</button>'
            '<button class="btn btn-secondary scanbtn scanbtn-discard" data-action="discard" type="button">✕ Discard</button>'
            '</div>'
            '</div></div>'
        )

    scan_cards_html = "".join(scan_card(l) for l in scan_lots)
    scan_count = len(scan_lots)

    CHECKLIST_GROUPS = [
        ("Designers", dedupe_variants(kw.get("designers", []))),
        ("Models", dedupe_variants(kw.get("models", []))),
        ("Woods", ["jakaranda", "palisander", "afrormosia", "valnöt", "alm", "teak"]),
        ("Lazy-listing (the alpha terms)", kw.get("lazy_listing_terms", [])),
        ("Styles & types", kw.get("no_designer_items", [])),
    ]
    checklist_total = sum(len(items) for _, items in CHECKLIST_GROUPS)

    def checklist_group_html(label, items):
        rows = "".join(
            f'<div class="chk-row">'
            f'<input type="checkbox" data-term="{esc(t)}">'
            f'<span class="chk-term" data-copy="{esc(t)}" title="Click to copy &amp; mark checked" tabindex="0" role="button">{esc(t)}</span>'
            f'</div>'
            for t in items
        )
        return f'<div class="chk-group"><h5>{esc(label)} <span class="text-muted">({len(items)})</span></h5><div class="chk-list">{rows}</div></div>'

    checklist_html = "".join(checklist_group_html(label, items) for label, items in CHECKLIST_GROUPS)

    html_out = render(
        TEMPLATE,
        scan_total=str(scan_total),
        scan_count=str(scan_count),
        scan_cards_html=scan_cards_html or '<p class="text-muted">No scan results yet.</p>',
        checklist_total=str(checklist_total),
        checklist_html=checklist_html,
    )

    os.makedirs(OUT_DIR, exist_ok=True)
    os.makedirs(os.path.join(OUT_DIR, "site"), exist_ok=True)
    with open(os.path.join(OUT_DIR, "index.html"), "w", encoding="utf-8") as fh:
        fh.write(html_out)

    # Only the CSS gets copied in — not the rest of site/ (brand guide docs,
    # uploads, component reference pages aren't meant for a public site).
    import shutil
    shutil.copyfile(os.path.join(ROOT, "dashboard.css"), os.path.join(OUT_DIR, "dashboard.css"))
    shutil.copyfile(os.path.join(ROOT, "site", "styles.css"), os.path.join(OUT_DIR, "site", "styles.css"))

    print(f"wrote {os.path.join(OUT_DIR, 'index.html')}")
    print(f"  scan lots: {scan_count} shown / {scan_total} archived · checklist terms: {checklist_total}")


if __name__ == "__main__":
    main()
